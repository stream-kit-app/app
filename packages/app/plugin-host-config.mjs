import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const configDir = path.dirname(fileURLToPath(import.meta.url));

export const PLUGIN_HOST_SVELTE_SUBPATHS = [
	'internal/disclose-version',
	'internal/client',
	'reactivity'
];

/** UI subpaths that are exported but should not be pre-built in the plugin host. */
export const PLUGIN_HOST_UI_EXCLUDED_SUBPATHS = new Set(['monaco']);

export const PLUGIN_HOST_ROOT_IMPORTS = [
	['@stream-kit/plugin', 'plugin.js'],
	['@stream-kit/plugin/action', 'action.js'],
	['@stream-kit/core', 'core.js'],
	['@iconify/svelte', '@iconify/svelte.js'],
	['svelte', 'svelte.js']
];

export const PLUGIN_HOST_EXTERNAL_PREFIXES = [
	'@stream-kit/core',
	'@stream-kit/ui',
	'svelte',
	'bits-ui',
	'runed',
	'@iconify/svelte'
];

export const PLUGIN_HOST_EXTERNALS = new Set([
	'@stream-kit/plugin',
	'@stream-kit/plugin/action',
	'@stream-kit/core',
	'svelte',
	'bits-ui',
	'runed',
	'@iconify/svelte'
]);

export function getWorkspaceRoot(fromDir = configDir) {
	return path.resolve(fromDir, '../..');
}

export function getUiPackageJsonPath(workspaceRoot = getWorkspaceRoot()) {
	return path.resolve(workspaceRoot, 'packages/ui/package.json');
}

export function getUiSubpaths(workspaceRoot = getWorkspaceRoot()) {
	const pkg = JSON.parse(readFileSync(getUiPackageJsonPath(workspaceRoot), 'utf8'));

	return Object.entries(pkg.exports)
		.filter(([key, value]) => {
			if (!key.startsWith('./') || key === './types' || key.endsWith('/types')) {
				return false;
			}

			const subpath = key.slice(2);
			if (PLUGIN_HOST_UI_EXCLUDED_SUBPATHS.has(subpath)) {
				return false;
			}

			return typeof value === 'object' && value !== null && 'svelte' in value;
		})
		.map(([key]) => key.slice(2))
		.sort();
}

export function isPluginHostExternal(id) {
	if (PLUGIN_HOST_EXTERNALS.has(id)) {
		return true;
	}

	return PLUGIN_HOST_EXTERNAL_PREFIXES.some(
		(prefix) => id === prefix || id.startsWith(`${prefix}/`)
	);
}

export function getGeneratedVendorDir(appRoot = configDir) {
	return path.resolve(appRoot, 'src/lib/core/plugins/host/vendor/_generated');
}

export function syncPluginHostVendorStubs(appRoot = configDir, workspaceRoot = getWorkspaceRoot()) {
	const vendorDir = getGeneratedVendorDir(appRoot);
	const uiSubpaths = getUiSubpaths(workspaceRoot);

	mkdirSync(vendorDir, { recursive: true });

	writeFileSync(path.join(vendorDir, 'svelte.ts'), `export * from 'svelte';\n`);
	writeFileSync(path.join(vendorDir, 'iconify-svelte.ts'), `export { default } from '@iconify/svelte';\n`);

	for (const subpath of PLUGIN_HOST_SVELTE_SUBPATHS) {
		const fileName = `svelte-${subpath.replace(/\//g, '-')}.ts`;
		writeFileSync(path.join(vendorDir, fileName), `export * from 'svelte/${subpath}';\n`);
	}

	for (const subpath of uiSubpaths) {
		writeFileSync(path.join(vendorDir, `ui-${subpath}.ts`), `export * from '@stream-kit/ui/${subpath}';\n`);
	}

	return { vendorDir, uiSubpaths };
}

export function createPluginHostViteEntries(vendorDir, uiSubpaths = getUiSubpaths()) {
	const entries = {
		svelte: path.join(vendorDir, 'svelte.ts'),
		'@iconify/svelte': path.join(vendorDir, 'iconify-svelte.ts')
	};

	for (const subpath of PLUGIN_HOST_SVELTE_SUBPATHS) {
		const fileName = `svelte-${subpath.replace(/\//g, '-')}.ts`;
		entries[`svelte/${subpath}`] = path.join(vendorDir, fileName);
	}

	for (const subpath of uiSubpaths) {
		entries[`@stream-kit/ui/${subpath}`] = path.join(vendorDir, `ui-${subpath}.ts`);
	}

	return entries;
}

export function syncPluginHostModules(appRoot = configDir, workspaceRoot = getWorkspaceRoot()) {
	const { uiSubpaths } = syncPluginHostVendorStubs(appRoot, workspaceRoot);
	const generatedPath = path.resolve(appRoot, 'plugin-host-modules.generated.js');
	const dtsPath = path.resolve(appRoot, 'plugin-host-modules.generated.d.ts');

	const js = `// AUTO-GENERATED by packages/app/scripts/build-plugin-host.mjs — do not edit.
export const PLUGIN_HOST_UI_SUBPATHS = ${JSON.stringify(uiSubpaths, null, '\t')};

export const PLUGIN_HOST_SVELTE_SUBPATHS = ${JSON.stringify(PLUGIN_HOST_SVELTE_SUBPATHS, null, '\t')};
`;

	const dts = `// AUTO-GENERATED by packages/app/scripts/build-plugin-host.mjs — do not edit.
export declare const PLUGIN_HOST_UI_SUBPATHS: readonly ${uiSubpaths.map((subpath) => `'${subpath}'`).join(' | ') || 'string'}[];

export declare const PLUGIN_HOST_SVELTE_SUBPATHS: readonly ${PLUGIN_HOST_SVELTE_SUBPATHS.map((subpath) => `'${subpath}'`).join(' | ')};
`;

	writeFileSync(generatedPath, js);
	writeFileSync(dtsPath, dts);

	return { uiSubpaths, generatedPath };
}

export function syncDevPluginsJson(workspaceRoot = getWorkspaceRoot()) {
	const pluginsDir = path.resolve(workspaceRoot, 'plugins');
	const configPath = path.resolve(workspaceRoot, 'dev-plugins.json');

	if (!existsSync(pluginsDir)) {
		return null;
	}

	const plugins = readdirSync(pluginsDir, { withFileTypes: true })
		.filter((entry) => entry.isDirectory())
		.map((entry) => entry.name)
		.filter((name) => existsSync(path.join(pluginsDir, name, 'manifest.json')))
		.sort((a, b) => {
			if (a === 'core') return -1;
			if (b === 'core') return 1;
			return a.localeCompare(b);
		})
		.map((name) => `plugins/${name}`);

	const config = {
		plugins
	};

	writeFileSync(configPath, `${JSON.stringify(config, null, '\t')}\n`);

	return configPath;
}
